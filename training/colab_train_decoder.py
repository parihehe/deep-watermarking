def _predict_bits(
    model: nn.Module, loader, device: str
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    model.eval()
    probs, labels, img_ids = [], [], []
    with torch.no_grad():
        for windows, lbl, img in loader:
            p = torch.sigmoid(model(windows.to(device)).squeeze(1)).cpu().numpy()
            probs.append(p)
            labels.append(lbl.numpy())
            img_ids.append(img.numpy())
    return (np.concatenate(probs), np.concatenate(labels), np.concatenate(img_ids))


def predict_windows(model: nn.Module, windows: np.ndarray, device: str) -> np.ndarray:
    model.eval()
    out = []
    with torch.no_grad():
        for i in range(0, len(windows), 256):
            chunk = torch.from_numpy(windows[i : i + 256]).float().to(device)
            out.append(torch.sigmoid(model(chunk).squeeze(1)).cpu().numpy())
    return np.concatenate(out)


def evaluate_model(
    cfg: PipelineConfig,
    cache: dict[str, Path],
    trained,
    *,
    device: str = "auto",
    threshold: float = 0.78,
) -> dict:
    """Stage C: honest test-set numbers - bit level, full registry-ID recovery,
    controlled false-positive rate, and a clean-image sanity confirmation."""
    if device == "auto":
        device = "cuda" if torch.cuda.is_available() else ("mps" if torch.backends.mps.is_available() else "cpu")
    model = trained["model"]

    _, _, test_loader = build_loaders(cfg, cache)
    probs_test, labels_test, img_ids_test = _predict_bits(model, test_loader, device)
    bit_metrics = _binary_metrics(
        torch.from_numpy((probs_test > 0.5).astype(np.float32)),
        torch.from_numpy(labels_test.astype(np.float32)),
    )
    print(f"[eval] test bit-level: {bit_metrics}")

    # Full-payload registry-ID recovery (decode via the real codec).
    recovered = []
    n_ids_ok = n_registered = 0
    for img_id in np.unique(img_ids_test):
        mask = img_ids_test == img_id
        pred_bits = (probs_test[mask] > 0.5).astype(int).tolist()
        true_bits = labels_test[mask].astype(int).tolist()
        true_id, _, _ = id_registry.decode_id_bits(true_bits)
        try:
            pred_id, mean_conf, min_conf = id_registry.decode_id_bits(pred_bits)
            valid = True
        except ValueError:
            pred_id, mean_conf, min_conf, valid = -1, 0.0, 0.0, False
        exact = valid and pred_id == true_id
        n_ids_ok += int(exact)
        n_registered += int(valid and min_conf >= threshold)
        recovered.append(
            {
                "image_id": int(img_id),
                "true_id": int(true_id),
                "pred_id": int(pred_id),
                "exact": exact,
                "valid": valid,
                "mean_conf": float(mean_conf),
                "min_conf": float(min_conf),
                "ber": float(1.0 - float(np.mean(mask & (pred_bits == true_bits)))),
            }
        )
    full_payload = {
        "test_images": len(recovered),
        "exact_id": n_ids_ok,
        "exact_id_rate": n_ids_ok / max(len(recovered), 1),
        "registered_at_threshold": n_registered,
        "registered_rate": n_registered / max(len(recovered), 1),
        "threshold_used": threshold,
        "mean_min_conf": float(np.mean([r["min_conf"] for r in recovered])),
        "per_image": recovered,
    }
    print(
        f"[eval] full-payload ID recovery: exact={n_ids_ok}/{len(recovered)} "
        f"registered={n_registered}/{len(recovered)} @ threshold {threshold}"
    )

    # Controlled test on image files currently in the repo - skip in smoke runs.
    return {
        "bit_level": bit_metrics,
        "full_payload": full_payload,
        "false_positives": _false_positive_test(cfg, cache, model, device, threshold),
        "robustness": _robustness_mini(cfg, cache, model, device, n=8),
        "data_quality": None,
    }


def _false_positive_test(
    cfg: PipelineConfig, cache: dict[str, Path], model, device: str, threshold: float
) -> dict:
    """Feed the decoder **clean, never-watermarked** test pixels. A registered
    ID at >= threshold is a false positive (spurious ownership match)."""
    clean_npz = cache.get("clean_test")
    loader = torch.utils.data.DataLoader(
        WindowArrayDataset(clean_npz), batch_size=cfg.batch_size, shuffle=False
    )
    probs, _, img_ids = _predict_bits(model, loader, device)
    fps = 0
    hits = []
    for img_id in np.unique(img_ids):
        mask = img_ids == img_id
        bits = (probs[mask] > 0.5).astype(int).tolist()
        try:
            pred_id, _, min_conf = id_registry.decode_id_bits(bits)
            registered = min_conf >= threshold
        except ValueError:
            pred_id, min_conf, registered = -1, 0.0, False
        if registered:
            fps += 1
            hits.append(
                {"image_id": int(img_id), "pred_id": int(pred_id), "min_conf": float(min_conf)}
            )
    n = img_ids.max() - img_ids.min() + 1 if len(img_ids) else 0
    result = {
        "clean_test_images": len(np.unique(img_ids)),
        "false_positive_registrations": fps,
        "false_positive_rate": fps / max(len(np.unique(img_ids)), 1),
        "threshold_used": threshold,
        "hits": hits,
    }
    print(f"[eval] false positives on clean images: {fps}/{n} @ threshold {threshold}")
    return result


def _robustness_mini(
    cfg: PipelineConfig, cache: dict[str, Path], model, device: str, n: int = 8
) -> dict:
    """Image-level re-embed smoke: embed real payloads into clean test images,
    apply common post-processing (PNG re-encode, JPEG q90, mild blur), then
    blind-decode - reports BER. Uses the same authoritative feature mapping."""
    clean_npz = cache.get("clean_test")
    if clean_npz is None:
        return {}
    # rebuild clean test images from the split manifest when available
    split_json = Path(cfg.out_dir) / "dataset_split.json"
    if not split_json.is_file():
        return {"skipped": "dataset_split.json missing"}
    split_data = json.loads(split_json.read_text(encoding="utf-8"))
    files = (split_data.get("all_files") or {}).get("test", []) or split_data.get("test", [])
    if not files or not Path(files[0]).is_file():
        return {"skipped": "test image files unavailable on this machine"}

    results = []
    for idx, path in enumerate(files[:n]):
        payload = _payload_for(idx, cfg)
        bgr = cv2.imread(path, cv2.IMREAD_COLOR)
        rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)
        if rgb.shape[:2] != (cfg.image_size, cfg.image_size):
            rgb = cv2.resize(rgb, (cfg.image_size, cfg.image_size), interpolation=cv2.INTER_AREA)
        wm = embed(rgb, payload, cfg.embed_config()).watermarked_image
        variants = {"png_reencode": None, "jpeg_q90": None, "blur_k3": None}
        wm_bgr = cv2.cvtColor(wm, cv2.COLOR_RGB2BGR)
        _ok, buf = cv2.imencode(".png", wm_bgr)
        variants["png_reencode"] = cv2.imdecode(buf, cv2.IMREAD_COLOR)
        __, buf = cv2.imencode(".jpg", wm_bgr, [cv2.IMWRITE_JPEG_QUALITY, 90])
        variants["jpeg_q90"] = cv2.imdecode(buf, cv2.IMREAD_COLOR)
        variants["blur_k3"] = cv2.GaussianBlur(wm_bgr, (3, 3), 0)

        per = {}
        for name, arr in variants.items():
            arr_rgb = cv2.cvtColor(arr, cv2.COLOR_BGR2RGB)
            sigma = luminance_ll_singular_values(arr_rgb, cfg.model_config())
            windows = np.stack(
                [
                    bit_window_singular_values(sigma, i, cfg.model_config())
                    for i in range(cfg.bit_length)
                ]
            )
            probs = predict_windows(model, windows, device)
            bits = (probs > 0.5).astype(int)
            ber = float(np.mean(bits != np.asarray(payload)))
            per[name] = {"bit_acc": 1.0 - ber, "ber": ber}
        results.append({"image_id": idx, "variants": per})
    return {"images": results}


