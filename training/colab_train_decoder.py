def _png_id(path: Path) -> int:
    try:
        return int(path.stem)
    except ValueError:
        # kagglehub vendors sometimes prefix the folder name - take the last int.
        match = __import__("re").search(r"(\d+)$", path.stem)
        if not match:
            raise ColabPipelineError(f"unexpected DIV2K filename: {path.name}")
        return int(match.group(1))


def find_image_dirs(source: Path) -> tuple[Path, Path]:
    for train_name, valid_name in KAGGLE_LAYOUTS:
        train_dir, valid_dir = source / train_name, source / valid_name
        if train_dir.is_dir() and valid_dir.is_dir():
            return train_dir, valid_dir
    raise ColabPipelineError(
        f"could not find DIV2K train/valid folders under {source}. Expected one of "
        f"{['/'.join(p) for p in KAGGLE_LAYOUTS]}"
    )


def discover_div2k_pngs(source: Path) -> tuple[list[Path], list[Path]]:
    """Layout-agnostic DIV2K discovery.

    Recursively scans ``source`` (any nesting depth), extracts any still-zipped
    ``*.zip``/``*.archive`` files it finds (kagglehub mirrors often ship the
    official archives zipped one level deeper), and groups the 900 PNGs by their
    official image ID: 0001-0800 -> train, 0801-0900 -> valid. Folder names are
    irrelevant - the ID is authoritative, so ``DIV2K_train_HR``,
    ``train``/``valid``, flat or nested layouts all work identically.
    """
    source = Path(source)
    for archive in list(source.rglob("*")):
        if (
            archive.is_file()
            and archive.suffix.lower() in (".zip", ".archive")
        ):
            try:
                with zipfile.ZipFile(archive) as zf:
                    zf.extractall(archive.parent)
                archive.unlink(missing_ok=True)
                print(f"[div2k] extracted nested archive: {archive.name}")
            except zipfile.BadZipFile:
                continue

    by_id: dict[int, Path] = {}
    for p in source.rglob("*.png"):
        if not p.is_file():
            continue
        try:
            by_id.setdefault(_png_id(p), p)
        except ColabPipelineError:
            continue
    missing = [i for i in range(1, 901) if i not in by_id]
    if missing:
        raise ColabPipelineError(
            f"official DIV2K image set incomplete: {len(missing)} of 900 images "
            f"missing (first:{missing[:10]}). The source layout or mirror differs "
            "- use SOURCE='official' with the official archives, or SOURCE='fake'."
        )
    train = [by_id[i] for i in range(1, 801)]
    valid = [by_id[i] for i in range(801, 901)]
    print(
        f"[div2k] discovered {len(train) + len(valid)} images under {source} "
        f"(train={len(train)} valid={len(valid)})"
    )
    return train, valid


def download_div2k(
    config: PipelineConfig,
    *,
    use_kagglehub: bool = True,
    fake: bool = False,
) -> tuple[list[Path], list[Path]]:
    """Return ``(train_pngs, valid_pngs)`` - the official 800 + 100 HR files.

    ``fake=True`` (dev/smoke): builds a throwaway DIV2K-shaped tree of small
    synthetic 256x256 PNGs in a temp dir so the whole pipeline can be verified
    on a CPU laptop without a real download. Returns file lists in both modes.
    """
    if fake:
        import tempfile

        tmp = Path(tempfile.mkdtemp(prefix="div2k_fake_")) / "div2k_hr"
        train_dir, valid_dir = tmp / "DIV2K_train_HR", tmp / "DIV2K_valid_HR"
        train_dir.mkdir(parents=True), valid_dir.mkdir(parents=True)
        rng = np.random.default_rng(1234)
        base = (rng.random((256, 256, 3)) * 255).astype(np.uint8)
        total = 900
        for i in range(1, total + 1):
            noise = np.roll(base, i, axis=(0, 1))
            target = train_dir if i <= 800 else valid_dir
            cv2.imwrite(str(target / f"{i:04d}.png"), cv2.cvtColor(noise, cv2.COLOR_RGB2BGR))
        train, valid = discover_div2k_pngs(tmp)
        t0 = time.time()
        print(f"[div2k] fake DIV2K tree written to {tmp} in {time.time() - t0:.1f}s")
        return train, valid

    if use_kagglehub:
        if kagglehub is None:
            raise ColabPipelineError(
                "kagglehub is not installed - run `pip install kagglehub` or pass "
                "use_kagglehub=False and supply the official archives."
            )
        print(f"[div2k] kagglehub.dataset_download({KAGGLE_DATASET!r}) ...")
        try:
            source = Path(kagglehub.dataset_download(KAGGLE_DATASET))
        except Exception as exc:
            raise ColabPipelineError(f"kagglehub download failed: {exc}") from exc
        print(f"[div2k] downloaded to {source}")
    else:
        raw = Path(config.project_root) / "data" / "raw"
        if (raw / "div2k_hr").is_dir():
            source = raw / "div2k_hr"
        elif any(raw.rglob("*.png")):
            source = raw
        else:
            raise ColabPipelineError(
                "no DIV2K images found under data/raw (run scripts/setup_div2k.py "
                "locally first, or pass use_kagglehub=True)."
            )
    return discover_div2k_pngs(source)


def make_split(
    train_files: list[Path], valid_files: list[Path], *, mode: str, limits: dict[str, int | None]
) -> tuple[dict[str, list[str]], int]:
    """Deterministic, image-level-disjoint id-based split (a file in one split only).

    mode "700": train = 0001-0700 (official train head), validation = 0701-0800
                (official train tail), test = 0801-0900 (official valid). Same
                test set as the local project.
    mode "800": train = 0001-0800 (whole official train), validation = 0801-0850,
                test = 0851-0900 (both carved from the official valid set).
    """
    by_id = {_png_id(p): str(p) for p in train_files + valid_files}
    ids = sorted(by_id)
    if mode == "800":
        train = [i for i in ids if 1 <= i <= 800]
        validation = [i for i in ids if 801 <= i <= 850]
        test = [i for i in ids if 851 <= i <= 900]
    else:
        train = [i for i in ids if 1 <= i <= 700]
        validation = [i for i in ids if 701 <= i <= 800]
        test = [i for i in ids if 801 <= i <= 900]
    missing = (set(train) | set(validation) | set(test)) - set(ids)
    if missing:
        raise ColabPipelineError(f"split bands missing from the download: {sorted(missing)}")
    groups = {"train": train, "validation": validation, "test": test}
    kept = {}
    for name, band in groups.items():
        cap = limits.get(name)
        selected = band[:cap] if cap else band
        kept[name] = sorted(selected)
    return {name: [by_id[i] for i in band] for name, band in kept.items()}, len(by_id)


