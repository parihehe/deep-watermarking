def package_artifacts(cfg: PipelineConfig, *, device: str = "cpu") -> str:
    """Build the self-contained windowed_cnn_model_package.zip: checkpoint(s),
    normalization, decoder config (model + bit_length + image_size), training
    config, split, metrics, history."""
    out_dir = Path(cfg.out_dir)
    import zipfile

    decoder_config = {
        "decoder_class": "WindowedCNNExtractor",
        "bit_length": cfg.bit_length,
        "window_size": cfg.window_size,
        "image_size": cfg.image_size,
        "alpha": cfg.alpha,
        "wavelet": "haar",
        "subband": "LL",
        "input_transform": "per_window_log1p_standardised_inside_bit_window_singular_values",
        "reliability_threshold": 0.78,
    }

    zip_path = out_dir / "windowed_cnn_model_package.zip"
    # normalization.npz is produced by the cache stage (cache_dir), not the
    # training stage - normalise its location so the package is self-contained.
    norm_src = out_dir / "normalization.npz"
    if not norm_src.is_file():
        cache_norm = Path(cfg.cache_dir) / "normalization.npz"
        if cache_norm.is_file():
            import shutil

            shutil.copy2(cache_norm, norm_src)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        wm_names = ["windowed_cnn_best.pt", "windowed_cnn_last.pt"]
        for name in wm_names:
            p = out_dir / name
            if p.is_file():
                zf.write(p, name)
        href = out_dir / "decoder_config.json"
        href.write_text(json.dumps(decoder_config, indent=2), encoding="utf-8")
        for name in [
            "decoder_config.json",
            "normalization.npz",
            "training_config.json",
            "dataset_split.json",
            "metrics.json",
            "training_history.csv",
        ]:
            p = out_dir / name
            if p.is_file():
                zf.write(p, name)
    print(f"[package] {zip_path} ({zip_path.stat().st_size / 1e6:.2f} MB)")
    return str(zip_path)


def load_checkpoints_into_repo(cfg: PipelineConfig) -> str:
    """Copy packaged artifacts into the project's models/experimental/windowed_cnn
    directory (the local app's decoder_loader looks here)."""
    import shutil

    dest = (Path(cfg.project_root) / "models" / "experimental" / "windowed_cnn").resolve()
    dest.mkdir(parents=True, exist_ok=True)
    moved = []
    for name in [
        "windowed_cnn_best.pt",
        "windowed_cnn_last.pt",
        "decoder_config.json",
        "normalization.npz",
        "training_config.json",
        "dataset_split.json",
        "metrics.json",
        "training_history.csv",
    ]:
        src = Path(cfg.out_dir) / name
        if src.is_file():
            shutil.copy2(src, dest / name)
            moved.append(str(dest / name))
    print(f"[repo] artifacts copied into the local project: {moved}")
    return str(dest)


