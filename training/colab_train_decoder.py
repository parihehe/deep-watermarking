class WindowArrayDataset(torch.utils.data.Dataset):
    def __init__(self, npz: Path):
        data = np.load(str(npz), allow_pickle=False)
        self.windows = torch.from_numpy(data["windows"].astype(np.float32))
        self.labels = torch.from_numpy(data["labels"].astype(np.float32))
        self.img_ids = torch.from_numpy(data["img_ids"].astype(np.int64))

    def __len__(self) -> int:
        return len(self.windows)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor, int]:
        return self.windows[idx], self.labels[idx], int(self.img_ids[idx])


def build_loaders(cfg: PipelineConfig, cache: dict[str, Path], *, shuffle_train: bool = True):
    train = torch.utils.data.DataLoader(
        WindowArrayDataset(cache["train"]),
        batch_size=cfg.batch_size,
        shuffle=shuffle_train,
        num_workers=cfg.num_workers,
    )
    val = torch.utils.data.DataLoader(
        WindowArrayDataset(cache["validation"]),
        batch_size=cfg.batch_size,
        shuffle=False,
        num_workers=cfg.num_workers,
    )
    test = torch.utils.data.DataLoader(
        WindowArrayDataset(cache["test"]),
        batch_size=cfg.batch_size,
        shuffle=False,
        num_workers=cfg.num_workers,
    )
    return train, val, test


