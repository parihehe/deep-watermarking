# Training (Stage B)
# ---------------------------------------------------------------------------


def _binary_metrics(logits: torch.Tensor, targets: torch.Tensor) -> dict:
    preds = (torch.sigmoid(logits) > 0.5).float()
    ok = preds.eq(targets)
    n = targets.numel()
    acc = float(ok.sum().item()) / max(n, 1)
    ber = 1.0 - acc
    # confusion (flat: tn,fp,fn,tp counts)
    tp = int(((preds == 1) & (targets == 1)).sum().item())
    tn = int(((preds == 0) & (targets == 0)).sum().item())
    fp = int(((preds == 1) & (targets == 0)).sum().item())
    fn = int(((preds == 0) & (targets == 1)).sum().item())
    precision = tp / max(tp + fp, 1)
    recall = tp / max(tp + fn, 1)
    f1 = 2 * precision * recall / max(precision + recall, 1e-9)
    return {
        "bit_accuracy": acc,
        "ber": ber,
        "tn": tn,
        "fp": fp,
        "fn": fn,
        "tp": tp,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "n_bits": n,
    }


def _evaluate_arrays(model: nn.Module, loader, device: str) -> dict:
    model.eval()
    loss = nn.BCEWithLogitsLoss()
    tot, n = 0.0, 0
    with torch.no_grad():
        for windows, labels, _ in loader:
            windows = windows.to(device)
            labels = labels.to(device)
            logits = model(windows).squeeze(1)
            tot += loss(logits, labels).item() * len(windows)
            n += len(windows)
    return {"loss": tot / max(n, 1)}


def _train_epoch(model, loader, loss_fn, optimizer, cfg, device) -> dict:
    model.train()
    running, bits, correct = 0.0, 0, 0
    for windows, labels, _ in loader:
        windows, labels = windows.to(device), labels.to(device)
        optimizer.zero_grad(set_to_none=True)
        logits = model(windows).squeeze(1)
        loss = loss_fn(logits, labels)
        loss.backward()
        optimizer.step()
        running += loss.item() * len(windows)
        bits += labels.numel()
        correct += int((torch.sigmoid(logits.detach()) > 0.5).float().eq(labels).sum().item())
    return {"train_loss": running / max(bits, 1), "train_bit_acc": correct / max(bits, 1)}


def train_model(
    cfg: PipelineConfig,
    cache: dict[str, Path],
    *,
    device: str = "auto",
    resume: str | None = None,
) -> dict[str, object]:
    """Stage B: train the windowed CNN on the cached windows. Saves best+last
    checkpoints, history csv and training_config.json. Auto-resumes from an
    existing best checkpoint if present and ``resume`` is not given."""
    if device == "auto":
        device = "cuda" if torch.cuda.is_available() else ("mps" if torch.backends.mps.is_available() else "cpu")
    _seed_everything(cfg.seed)

    out_dir = Path(cfg.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    best_path = out_dir / "windowed_cnn_best.pt"
    last_path = out_dir / "windowed_cnn_last.pt"
    history_path = out_dir / "training_history.csv"

    model = WindowedCNNExtractor(cfg.model_config()).to(device)
    start_epoch, best_bit_acc, best_epoch = 0, -1.0, -1

    train_loader, val_loader, _ = build_loaders(cfg, cache)

    if resume:
        if not Path(resume).is_file():
            raise ColabPipelineError(f"--resume checkpoint not found: {resume}")
        model, meta = load_windowed_checkpoint(resume, map_location=device)
        model = model.to(device)
        start_epoch = int(meta.get("epoch", 0)) + 1
        best_bit_acc = float(meta.get("best_val_bit_acc", -1.0))
        best_epoch = int(meta.get("best_epoch", -1))
        print(
            f"[train] resuming from {resume} at epoch {start_epoch} "
            f"(prior best val_bit_acc={best_bit_acc:.4f} at epoch {best_epoch})"
        )
    elif best_path.is_file():
        model, meta = load_windowed_checkpoint(str(best_path), map_location=device)
        model = model.to(device)
        start_epoch = int(meta.get("epoch", 0)) + 1
        best_bit_acc = float(meta.get("best_val_bit_acc", -1.0))
        best_epoch = int(meta.get("best_epoch", -1))
        print(
            f"[train] existing best checkpoint found -> resuming at epoch {start_epoch} "
            f"(use --resume to override). best val_bit_acc={best_bit_acc:.4f}"
        )

    loss_fn = nn.BCEWithLogitsLoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=cfg.lr)
    params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(
        f"[train] device={device} params={params:,} bits={cfg.bit_length} "
        f"window={cfg.window_size} alpha={cfg.alpha} epochs={start_epoch}..{cfg.epochs}"
    )

    common_extra = {
        "bit_length": cfg.bit_length,
        "window_size": cfg.window_size,
        "image_size": cfg.image_size,
        "train_config": asdict(cfg),
    }
    rows: list[dict] = []
    no_improve = 0
    early_stopped = False

    def _val_metrics() -> dict:
        model.eval()
        vl, tot_loss, n = [], 0.0, 0
        with torch.no_grad():
            for w, l, _ in val_loader:
                logits = model(w.to(device)).squeeze(1)
                vl.append((logits.cpu(), l))
                tot_loss += nn.functional.binary_cross_entropy_with_logits(
                    logits, l.to(device)
                ).item() * len(w)
                n += len(w)
        logits = torch.cat([x for x, _ in vl], dim=0)
        labels = torch.cat([y for _, y in vl], dim=0)
        metrics = _binary_metrics(logits, labels)
        metrics["loss"] = tot_loss / max(n, 1)
        return metrics

    if best_bit_acc < 0:
        print(f"[train] epoch 0 (init) val_loss={_val_metrics()['loss']:.4f}")

    for epoch in range(start_epoch, cfg.epochs + 1):
        t0 = time.time()
        tr = _train_epoch(model, train_loader, loss_fn, optimizer, cfg, device)
        vm = _val_metrics()
        row = {
            "epoch": epoch,
            **{k: round(v, 6) if isinstance(v, float) else v for k, v in tr.items()},
            "val_loss": round(vm["loss"], 6),
            **{
                f"val_{k}": (round(v, 6) if isinstance(v, float) else v)
                for k, v in vm.items()
                if k != "n_bits"
            },
        }
        rows.append(row)
        improved = not best_path.is_file() or vm["bit_accuracy"] > best_bit_acc + 1e-6
        if improved:
            best_bit_acc, best_epoch = vm["bit_accuracy"], epoch
            no_improve = 0
            save_windowed_checkpoint(
                str(best_path),
                model,
                extra={
                    **common_extra,
                    "epoch": epoch,
                    "val_metrics": vm,
                    "best_val_bit_acc": best_bit_acc,
                    "best_epoch": best_epoch,
                },
            )
            print(
                f"[train] epoch {epoch:2d} val_bit_acc={vm['bit_accuracy']:.4f} "
                f"ber={vm['ber']:.4f} f1={vm['f1']:.4f} ({time.time() - t0:.1f}s)  *BEST*"
            )
        else:
            no_improve += 1
            print(
                f"[train] epoch {epoch:2d} val_bit_acc={vm['bit_accuracy']:.4f} "
                f"ber={vm['ber']:.4f} f1={vm['f1']:.4f} ({time.time() - t0:.1f}s)"
            )
            if no_improve >= cfg.patience:
                early_stopped = True
                print(f"[train] early stopping after {epoch} epochs (patience {cfg.patience})")
                break
        save_windowed_checkpoint(
            str(last_path),
            model,
            extra={
                **common_extra,
                "epoch": epoch,
                "val_metrics": vm,
                "best_val_bit_acc": best_bit_acc,
                "best_epoch": best_epoch,
            },
        )

    with history_path.open("w", newline="", encoding="utf-8") as fh:
        if rows:
            w = csv.DictWriter(fh, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)

    training_config = {
        "epochs": cfg.epochs,
        "batch_size": cfg.batch_size,
        "lr": cfg.lr,
        "patience": cfg.patience,
        "seed": cfg.seed,
        "device": device,
        "bit_length": cfg.bit_length,
        "window_size": cfg.window_size,
        "image_size": cfg.image_size,
        "alpha": cfg.alpha,
        "model": "WindowedCNNExtractor (Conv1d 32/64, k=3, flatten, Dense 64, Dense 1)",
        "split_mode": cfg.split_mode,
        "best_epoch": best_epoch,
        "best_val_bit_acc": best_bit_acc,
    }
    (out_dir / "training_config.json").write_text(
        json.dumps(training_config, indent=2), encoding="utf-8"
    )
    if rows:
        (out_dir / "training_config.json").write_text(
            json.dumps({**training_config, "final_row": rows[-1]}, indent=2), encoding="utf-8"
        )

    return {
        "model": model,
        "best_path": str(best_path),
        "last_path": str(last_path),
        "history_path": str(history_path),
        "best_epoch": best_epoch,
        "best_val_bit_acc": best_bit_acc,
        "early_stopped": early_stopped,
        "rows": rows,
    }


