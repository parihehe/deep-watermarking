def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", default=str(_PROJECT_ROOT))
    parser.add_argument("--all", action="store_true", help="run the entire pipeline end-to-end")
    parser.add_argument(
        "--smoke",
        action="store_true",
        help="tiny train/val/test caps + 1 epoch to verify the pipeline",
    )
    parser.add_argument("--epochs", type=int)
    parser.add_argument("--split-mode", choices=["700", "800"])
    parser.add_argument(
        "--fake",
        action="store_true",
        help="dev-only: synthesize a small DIV2K-shaped tree and run on it",
    )
    parser.add_argument("--require-gpu", action="store_true")
    parser.add_argument("--resume")
    parser.add_argument("--out-dir", default="content/out")
    parser.add_argument("--cache-dir", default="content/windows")
    parser.add_argument(
        "--processed",
        action="store_true",
        help="use the local data/processed/<root> split dirs (train/validation/test) "
        "instead of downloading DIV2K",
    )
    args = parser.parse_args(argv)

    cfg = load_pipeline_config(
        args.project_root,
        {
            "epochs": args.epochs,
            "split_mode": args.split_mode,
            "out_dir": args.out_dir,
            "cache_dir": args.cache_dir,
            "train_images": (8 if args.smoke else None),
            "val_images": (4 if args.smoke else None),
            "test_images": (4 if args.smoke else None),
        },
    ).resolved()

    print(f"[env] {check_environment(require_gpu=args.require_gpu)}")
    if args.processed:
        processed = Path(cfg.processed_root)
        train_files = sorted(
            list((processed / cfg.train_split).glob("*.png"))
            + list((processed / cfg.validation_split).glob("*.png"))
        )
        valid_files = sorted((processed / cfg.test_split).glob("*.png"))
        if not train_files or not valid_files:
            raise ColabPipelineError(
                f"--processed: no images under {processed} - run scripts/setup_div2k.py first"
            )
    else:
        train_files, valid_files = download_div2k(cfg, use_kagglehub=not args.smoke, fake=args.fake)
    splits, total = make_split(
        train_files,
        valid_files,
        mode=cfg.split_mode,
        limits={"train": cfg.train_images, "validation": cfg.val_images, "test": cfg.test_images},
    )
    for name, files in splits.items():
        print(f"  split {name}: {len(files)} images")
    if args.smoke:
        print(f"[smoke] using {total} total files, split {cfg.split_mode}")
    write_dataset_split_json(cfg, splits)

    cache = generate_cache(cfg, splits)
    print(f"[cache] manifest hash: {cfg.config_hash()}")

    trained = train_model(cfg, cache, resume=args.resume)
    energy = evaluate_model(cfg, cache, trained)
    write_metrics(cfg, trained, energy)
    package_artifacts(cfg)
    load_checkpoints_into_repo(cfg)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
