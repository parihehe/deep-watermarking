"""Google-Colab GPU training pipeline for the experimental windowed 1D-CNN blind decoder.

PyTorch (matches the project's decoder stack). Trains the paper-style per-bit
windowed CNN on DIV2K where EVERY training sample is generated by the **actual,
existing project encoder** (`src.watermark.embed.embed` + the authoritative
`bit_window_singular_values` mapping), so the network learns the exact signal
the production embedder produces. Labels are the physical bits actually
embedded — never derived independently.

Notebook: ``training/colab_windowed_cnn_training.ipynb`` (thin wrapper around
this file). Run everything at once::

    python colab_train_decoder.py --project-root /content/deep-watermarking --all

or stage-by-stage from the notebook cells.

Key decisions (documented in docs/windowed_cnn.md and the notebook):

* **Frozen embedder, untouched.** This pipeline only *calls* the existing
  ``embed()``; it never re-implements or modifies the encoding mathematics.
* **Payloads from the real codec.** Training payloads come from
  ``id_registry.encode_id_bits(id)`` (interleaving + balanced XOR mask), so the
  learned bits ARE the physical bits the ownership/registry flow embeds.
* **One authoritative mapping.** ``bit_window_singular_values`` is shared by
  cache generation and live inference.
* **Split 700/100/100.** Released DIV2K has 900 images (train 800, valid 100);
  the master target "800 train / 100 val / 100 test" needs 1000, so test = the
  official valid set (IDs 0801-0900, same as the local project's test split),
  validation = the official-train tail (0701-0800), train = 0001-0700.
  Image-level separation is preserved (a file lives in exactly one split).
* **Cached windows.** Embedding-to-windows is a separate stage (npz cache with a
  config hash; rebuilt automatically when the config changes), so GPU training
  reads arrays instead of re-running the embedder.

Artifacts written to ``<out>/windowed_cnn``:
    windowed_cnn_best.pt / windowed_cnn_last.pt   (self-describing checkpoints)
    normalization.npz   (the feature transform the decoder expects)
    decoder_config.json (WindowedCNNConfig + bit_length + image_size)
    training_config.json
    training_history.csv
    dataset_split.json
    metrics.json
    windowed_cnn_model_package.zip  (self-contained download bundle)
"""

