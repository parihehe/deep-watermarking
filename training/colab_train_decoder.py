@dataclass(frozen=True)
class PipelineConfig:
    project_root: str
    bit_length: int = BIT_LENGTH
    window_size: int = WINDOW_SIZE
    image_size: int = IMAGE_SIZE
    alpha: float = ALPHA
    seed: int = SEED
    epochs: int = EPOCHS
    batch_size: int = BATCH_SIZE
    lr: float = LR
    patience: int = PATIENCE
    num_workers: int = 2
    out_dir: str = "content/out"
    split_mode: str = "700"  # "700" | "800" (see module docstring)
    cache_dir: str = "content/windows"
    train_images: int | None = None  # cap for smoke runs
    val_images: int | None = None
    test_images: int | None = None
    processed_root: str = "data/processed/div2k_256"
    train_split: str = "train"
    validation_split: str = "validation"
    test_split: str = "test"

    def embed_config(self) -> EmbedConfig:
        return EmbedConfig(
            wavelet="haar",
            subband="LL",
            mode="symmetric",
            alpha=self.alpha,
            bit_length=self.bit_length,
            start_sv_index=0,
        )

    def model_config(self) -> WindowedCNNConfig:
        return WindowedCNNConfig(
            bit_length=self.bit_length,
            window_size=self.window_size,
            wavelet="haar",
            mode="symmetric",
            subband="LL",
            image_size=self.image_size,
        )

    def resolved(self) -> PipelineConfig:
        (Path(self.project_root) / "data").resolve()
        return PipelineConfig(
            project_root=self.project_root,
            bit_length=self.bit_length,
            window_size=self.window_size,
            image_size=self.image_size,
            alpha=self.alpha,
            seed=self.seed,
            epochs=self.epochs,
            batch_size=self.batch_size,
            lr=self.lr,
            patience=self.patience,
            num_workers=self.num_workers,
            out_dir=str(Path(self.out_dir).resolve()),
            split_mode=self.split_mode,
            cache_dir=str(Path(self.cache_dir).resolve()),
            train_images=self.train_images,
            val_images=self.val_images,
            test_images=self.test_images,
            processed_root=str(Path(self.project_root, self.processed_root).resolve()),
            train_split=self.train_split,
            validation_split=self.validation_split,
            test_split=self.test_split,
        )

    def config_hash(self) -> str:
        raw = (self.bit_length, self.window_size, self.image_size, self.alpha, self.split_mode)
        return hashlib.sha256(json.dumps(raw, sort_keys=True).encode()).hexdigest()[:12]


def load_pipeline_config(project_root: str, overrides: dict | None = None) -> PipelineConfig:
    path = Path(project_root) / "configs" / "windowed_cnn.yaml"
    base = PipelineConfig(project_root=str(project_root))
    if path.is_file():
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))["windowed_cnn"]
        base = PipelineConfig(
            project_root=str(project_root),
            bit_length=int(raw.get("payload", {}).get("bit_length", BIT_LENGTH)),
            window_size=int(raw.get("model", {}).get("window_size", WINDOW_SIZE)),
            image_size=int(raw.get("model", {}).get("image_size", IMAGE_SIZE)),
            alpha=float(raw.get("embed", {}).get("alpha", ALPHA)),
            seed=int(raw.get("train", {}).get("seed", SEED)),
            epochs=int(raw.get("train", {}).get("epochs", EPOCHS)),
            batch_size=int(raw.get("train", {}).get("batch_size", BATCH_SIZE)),
            lr=float(raw.get("train", {}).get("lr", LR)),
            patience=int(raw.get("train", {}).get("early_stop_patience", PATIENCE)),
            num_workers=int(raw.get("train", {}).get("num_workers", 2)),
            split_mode=raw.get("data", {}).get("split_mode", "700"),
            processed_root=raw.get("data", {}).get("processed_root", "data/processed/div2k_256"),
            train_split=raw.get("data", {}).get("train_split", "train"),
            validation_split=raw.get("data", {}).get("validation_split", "validation"),
            test_split=raw.get("data", {}).get("test_split", "test"),
        )
    for key, value in (overrides or {}).items():
        if value is not None and hasattr(base, key):
            base = PipelineConfig(**{**asdict(base), key: value})
    return base


