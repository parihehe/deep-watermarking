def check_environment(require_gpu: bool = False) -> dict:
    """Return runtime facts; optionally hard-fail when CUDA is unavailable."""
    info = {
        "python": sys.version.split()[0],
        "torch": torch.__version__,
        "cuda_available": bool(torch.cuda.is_available()),
        "gpu_count": int(torch.cuda.device_count()) if torch.cuda.is_available() else 0,
        "gpu_name": torch.cuda.get_device_name(0)
        if torch.cuda.is_available() and torch.cuda.device_count() > 0
        else None,
        "numpy": np.__version__,
    }
    if require_gpu and not info["cuda_available"]:
        raise ColabPipelineError(
            "No CUDA GPU detected. Colab: Runtime -> Change runtime type -> T4 GPU "
            "(or A100). The pipeline trains without one, but is much slower."
        )
    return info


