def synthesize_windows(
    bgr_u8: np.ndarray,
    payload: list[int],
    cfg: PipelineConfig,
) -> np.ndarray:
    """Watermark real pixels with the frozen embedder, then build per-bit
    15-value windows exactly as live inference will. Returns (bit_length, 15)."""
    rgb = cv2.cvtColor(bgr_u8, cv2.COLOR_BGR2RGB)
    result = embed(rgb, payload, cfg.embed_config())
    wm = result.watermarked_image
    if wm.shape[:2] != (cfg.image_size, cfg.image_size):
        wm = cv2.resize(wm, (cfg.image_size, cfg.image_size), interpolation=cv2.INTER_AREA)
    sigma = luminance_ll_singular_values(wm, cfg.model_config())
    return np.stack(
        [bit_window_singular_values(sigma, i, cfg.model_config()) for i in range(len(payload))]
    )  # (bit_length, window_size)


def _payload_for(index: int, cfg: PipelineConfig) -> list[int]:
    """A real registry-ID payload (codec + XOR mask) seeded by index - the exact
    physical bits the ownership flow embeds (labels = these bits)."""
    id_ = int(index) % id_registry.MAX_ENTRIES
    return id_registry.encode_id_bits(id_)


def cache_manifest(cfg: PipelineConfig) -> dict:
    return {
        "config_hash": cfg.config_hash(),
        "bit_length": cfg.bit_length,
        "window_size": cfg.window_size,
        "image_size": cfg.image_size,
        "alpha": cfg.alpha,
        "wavelet": "haar",
        "subband": "LL",
        "split_mode": cfg.split_mode,
        "payload_source": "id_registry.encode_id_bits(id) for id in [0,16)",
        "feature_transform": "per-window log1p -> standardise inside bit_window_singular_values",
        "embedder": "src.watermark.embed.embed (frozen Phase 6) - unmodified",
    }


def generate_cache(cfg: PipelineConfig, splits: dict[str, list[str]]) -> dict[str, Path]:
    """Stage A: for every (split, image) put the ACTUAL payload through the ACTUAL
    embedder and cache the (windows, labels) arrays. Writes train/validation/test
    npz + a clean-test npz (never-watermarked pixels, for the false-positive test)
    + normalization.npz + dataset_split.json + manifest. Rebuilds when the config
    hash changes; otherwise reuses an existing cache."""
    cache_root = Path(cfg.cache_dir)
    cache_root.mkdir(parents=True, exist_ok=True)
    manifest = cache_manifest(cfg)
    out: dict[str, Path] = {}

    (cache_root / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    split_paths = {}
    for split, files in splits.items():
        split_paths[split] = files
        print(f"[cache] {split}: {len(files)} images")

    for split, files in split_paths.items():
        npz = cache_root / f"{split}.npz"
        n = len(files)
        if npz.is_file():
            loaded = np.load(npz, allow_pickle=False)
            if int(loaded["windows"].shape[0]) == n * cfg.bit_length:
                print(f"[cache] reuse {npz.name} ({n * cfg.bit_length} windows)")
                out[split] = npz
                continue
        print(f"[cache] generating {split} ({n} images x {cfg.bit_length} bits) ...")
        t0 = time.time()
        all_windows: list[np.ndarray] = []
        all_labels: list[np.ndarray] = []
        for idx, path in enumerate(files):
            bgr = cv2.imread(str(path), cv2.IMREAD_COLOR)
            if bgr is None:
                raise ColabPipelineError(f"unreadable image {path}")
            payload = _payload_for(idx, cfg)
            windows = synthesize_windows(bgr, payload, cfg)
            all_windows.append(windows)
            all_labels.append(np.asarray(payload, dtype=np.float32))
            if (idx + 1) % 100 == 0:
                print(f"  ... {idx + 1}/{n} images ({time.time() - t0:.1f}s)")
        W = np.concatenate(all_windows).astype(np.float32)  # (n*bits, window_size)
        L = np.concatenate(all_labels).astype(np.float32)  # (n*bits,)
        img_ids = np.repeat(np.arange(n), cfg.bit_length).astype(np.int64)
        np.savez(npz, windows=W, labels=L, img_ids=img_ids)
        out[split] = npz
        _sanity_checks(W, L, cfg, split)
        print(f"[cache] wrote {npz.name} [{W.shape}] in {time.time() - t0:.1f}s")

    # Clean (never-watermarked) test windows for the false-positive test.
    clean_npz = cache_root / "clean_test.npz"
    if not clean_npz.is_file():  # keep deterministic
        files = split_paths["test"]
        W, L0 = [], []
        for idx, path in enumerate(files):
            bgr = cv2.imread(str(path), cv2.IMREAD_COLOR)
            rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)
            if rgb.shape[:2] != (cfg.image_size, cfg.image_size):
                rgb = cv2.resize(
                    rgb, (cfg.image_size, cfg.image_size), interpolation=cv2.INTER_AREA
                )
            sigma = luminance_ll_singular_values(rgb, cfg.model_config())
            windows = np.stack(
                [
                    bit_window_singular_values(sigma, i, cfg.model_config())
                    for i in range(cfg.bit_length)
                ]
            )
            W.append(windows)
            L0.append(np.full(cfg.bit_length, np.nan, dtype=np.float32))  # no label
        C = np.concatenate(W).astype(np.float32)
        np.savez(
            clean_npz,
            windows=C,
            img_ids=np.repeat(np.arange(len(files)), cfg.bit_length).astype(np.int64),
            labels=np.concatenate(L0),
        )
        print(f"[cache] wrote {clean_npz.name} [{C.shape}] (clean, no watermark)")
    out["clean_test"] = clean_npz

    _write_normalization(cfg, out)
    return out


def _sanity_checks(W: np.ndarray, L: np.ndarray, cfg: PipelineConfig, split: str) -> None:
    if W.ndim != 2 or W.shape[1] != cfg.window_size:
        raise ColabPipelineError(
            f"{split}: window shape {W.shape}; expected (_, {cfg.window_size})"
        )
    if W.shape[0] != L.shape[0]:
        raise ColabPipelineError(f"{split}: {W.shape[0]} windows vs {L.shape[0]} labels mismatch")
    if not np.isfinite(W).all():
        raise ColabPipelineError(f"{split}: non-finite window values")
    if not np.isfinite(L).all():
        raise ColabPipelineError(f"{split}: non-finite labels")
    frac1 = float(L.mean())
    zeros = int((L == 0).sum())
    print(
        f"[sanity] {split}: finite={np.isfinite(W).all()} n={W.shape[0]} "
        f"label0={zeros} label1={W.shape[0] - zeros} frac1={frac1:.3f}"
    )


def _write_normalization(cfg: PipelineConfig, out: dict[str, Path]) -> None:
    """Record the feature transform the decoder expects.

    The model's input transform is the per-window ``log1p`` -> standardise that
    lives in ``bit_window_singular_values`` (identical at training and
    inference - this is the authoritative normalization, applied before the
    network and never recomputed from a single image). Global train-set stats
    are saved alongside for diagnostics / future feature engineering."""
    cache_root = Path(cfg.cache_dir)
    paths = (out.get("train"), out.get("validation"))
    means, stds, n = [], [], []
    for p in paths:
        if p and Path(p).is_file():
            a = np.load(p, allow_pickle=False)["windows"]
            means.append(a.mean(axis=0))
            stds.append(a.std(axis=0))
            n.append(len(a))
    if n:
        counts = np.asarray(n, dtype=np.float64)
        global_mean = np.average(np.asarray(means, dtype=np.float64), axis=0, weights=counts)
        # pooled std across splits (full-sample estimator for diagnostics only)
        var_part = (
            np.asarray(stds, dtype=np.float64) ** 2 + np.asarray(means, dtype=np.float64) ** 2
        ) * counts[:, None]
        pooled_std = np.sqrt(var_part.sum(axis=0) / counts.sum() - global_mean**2)
    else:
        global_mean = np.zeros(cfg.window_size)
        pooled_std = np.zeros(cfg.window_size)
    np.savez(
        cache_root / "normalization.npz",
        bit_length=cfg.bit_length,
        window_size=cfg.window_size,
        transform="per_window_log1p_standardised_inside_bit_window_singular_values",
        transform_applied_before_model=True,
        global_train_mean=global_mean.astype(np.float32),
        global_train_std=pooled_std.astype(np.float32),
    )
    print("[cache] normalization.npz written (per-window transform is authoritative)")


